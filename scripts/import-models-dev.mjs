#!/usr/bin/env node
// Builds the pinned model catalog snapshot from a locally downloaded models.dev `api.json`.
//
//   node scripts/import-models-dev.mjs <api.json> [--date YYYY-MM-DD] [--providers a,b,c]
//
// Run it in a reviewed pull request (see .github/workflows/catalog-refresh.yml) and commit the
// result. It is never run at application run time and the platform never fetches models.dev.
// The input is treated as untrusted data: only a whitelist of fields is copied, ids and names are
// restricted to a safe character set and prices must be plausible numbers.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

export const DEFAULT_PROVIDERS = ['anthropic', 'openai', 'azure', 'amazon-bedrock', 'openrouter'];
const ID = /^[A-Za-z0-9][A-Za-z0-9._:/@+-]{0,199}$/;
const MAX_PRICE_PER_MTOK = 1000;

const safeName = (v, fallback) => {
  const clean = (str) =>
    [...str]
      .filter((ch) => ch.charCodeAt(0) > 31 && ch.charCodeAt(0) !== 127 && !'<>`'.includes(ch))
      .join('');
  const s = typeof v === 'string' ? clean(v).trim() : '';
  return (s || fallback).slice(0, 120);
};
const nonNegativeInt = (v) => (Number.isInteger(v) && v > 0 ? v : undefined);
const price = (v) =>
  typeof v === 'number' && Number.isFinite(v) && v >= 0 && v <= MAX_PRICE_PER_MTOK ? v : undefined;

/** Pure conversion used by the script and by the unit tests. */
export function convert(api, wanted = DEFAULT_PROVIDERS) {
  const providers = {};
  for (const id of [...wanted].sort()) {
    const p = api?.[id];
    if (!p || typeof p !== 'object' || typeof p.models !== 'object') continue;
    const models = {};
    for (const mid of Object.keys(p.models).sort()) {
      const m = p.models[mid];
      if (!ID.test(mid) || !m || typeof m !== 'object') continue;
      const limit = {};
      const context = nonNegativeInt(m.limit?.context);
      const output = nonNegativeInt(m.limit?.output);
      if (context) limit.context = context;
      if (output) limit.output = output;
      const entry = { name: safeName(m.name, mid), limit };
      const input = price(m.cost?.input);
      const out = price(m.cost?.output);
      if (input !== undefined && out !== undefined) entry.cost = { input, output: out };
      if (typeof m.tool_call === 'boolean') entry.toolCall = m.tool_call;
      if (typeof m.reasoning === 'boolean') entry.reasoning = m.reasoning;
      models[mid] = entry;
    }
    providers[id] = { name: safeName(p.name, id), models };
  }
  return providers;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  const input = args.find((a) => !a.startsWith('--'));
  const opt = (name) => {
    const i = args.indexOf(`--${name}`);
    return i >= 0 ? args[i + 1] : undefined;
  };
  if (!input) {
    console.error(
      'usage: node scripts/import-models-dev.mjs <api.json> [--date YYYY-MM-DD] [--providers a,b]',
    );
    process.exit(2);
  }
  const raw = readFileSync(input);
  const providers = convert(
    JSON.parse(raw.toString('utf8')),
    opt('providers')?.split(',') ?? DEFAULT_PROVIDERS,
  );
  const out = {
    $comment:
      'Pinned snapshot of models.dev (MIT). Generated by scripts/import-models-dev.mjs in a reviewed pull request; never fetched at run time. Local and private models live in local.json.',
    source: 'models.dev',
    sourceUrl: 'https://models.dev/api.json',
    licence: 'MIT (https://github.com/sst/models.dev)',
    snapshotDate: opt('date') ?? new Date().toISOString().slice(0, 10),
    sha256: createHash('sha256').update(raw).digest('hex'),
    providers,
  };
  const target = new URL('../packages/providers/catalog/models.json', import.meta.url);
  writeFileSync(target, `${JSON.stringify(out, null, 2)}\n`);
  const n = Object.values(providers).reduce((s, p) => s + Object.keys(p.models).length, 0);
  console.log(
    `wrote ${Object.keys(providers).length} providers, ${n} models to ${target.pathname}`,
  );
}
