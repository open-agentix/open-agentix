#!/usr/bin/env node
// Generates the embedded schemas and the TypeScript types of the AWP manifest from the pinned schema.
//
//   node scripts/awp/generate-types.mjs           write packages/core/src/awp/generated/*
//   node scripts/awp/generate-types.mjs --check   exit 1 when a committed file differs (CI)
//
// Inputs (local files only, no network, no child processes):
//   packages/awp/vendor/awp-v1alpha1/schema/awp.v1alpha1.json   the vendored AWP schema (never edited)
//   packages/awp/extensions/openagentix-extensions.v1alpha1.json  the OpenAgentix extension schema
// The output is committed. It is never edited by hand: CI runs --check, so a hand edit fails.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const REPO_ROOT = fileURLToPath(new URL('../..', import.meta.url));
export const SCHEMA_FILE = 'packages/awp/vendor/awp-v1alpha1/schema/awp.v1alpha1.json';
export const EXTENSIONS_FILE = 'packages/awp/extensions/openagentix-extensions.v1alpha1.json';
export const OUT_DIR = 'packages/core/src/awp/generated';

const sha256 = (text) => createHash('sha256').update(text).digest('hex');
const header = (source, hash) =>
  `// GENERATED by scripts/awp/generate-types.mjs from ${source}\n` +
  `// (sha256 ${hash}). Do not edit: \`node scripts/awp/generate-types.mjs --check\` fails CI.\n\n`;

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const key = (k) => (IDENT.test(k) ? k : JSON.stringify(k));
const doc = (text, indent) =>
  typeof text === 'string' && text.length > 0
    ? `${indent}/** ${text.replace(/\s+/g, ' ').replace(/\*\//g, '* /')} */\n`
    : '';
const paren = (t) => (/[|&]/.test(t) ? `(${t})` : t);
const refName = (ref) => {
  const m = /^#\/\$defs\/([A-Za-z]+)$/.exec(ref);
  if (!m) throw new Error(`unsupported $ref: ${ref}`);
  return `Awp${m[1]}`;
};

/** TypeScript type of a (sub)schema. Conditional rules (if/then) are not expressed in types. */
function tsType(s, indent) {
  if (s === true || Object.keys(s).length === 0) return 'unknown';
  if (s.$ref) return refName(s.$ref);
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(' | ');
  if (s.oneOf || s.anyOf) return (s.oneOf ?? s.anyOf).map((x) => tsType(x, indent)).join(' | ');
  switch (s.type) {
    case 'string':
      return 'string';
    case 'number':
    case 'integer':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array':
      return `${paren(tsType(s.items ?? {}, indent))}[]`;
    case 'object':
      return objectType(s, indent);
    default:
      return 'unknown';
  }
}

function objectType(s, indent) {
  const props = Object.entries(s.properties ?? {});
  const lines = [];
  if (typeof s.additionalProperties === 'object' && props.length === 0) {
    return `{ [key: string]: ${tsType(s.additionalProperties, indent)} }`;
  }
  for (const [name, sub] of props) {
    const optional = (s.required ?? []).includes(name) ? '' : '?';
    lines.push(
      `${doc(sub.description, `${indent}  `)}${indent}  ${key(name)}${optional}: ${tsType(sub, `${indent}  `)};`,
    );
  }
  if (s.patternProperties && Object.keys(s.patternProperties).join() === '^x-') {
    lines.push(`${indent}  /** Extension field (spec 3.3): ignored unless interpreted. */`);
    lines.push(`${indent}  [extension: \`x-\${string}\`]: unknown;`);
  } else if (s.patternProperties) {
    throw new Error('unsupported patternProperties');
  }
  return lines.length === 0 ? '{}' : `{\n${lines.join('\n')}\n${indent}}`;
}

/** Refs reachable through if/then/else at the top of a definition (an entry that is one of several forms). */
function conditionalRefs(s) {
  const refs = [];
  const walk = (n) => {
    if (!n || typeof n !== 'object') return;
    if (n.$ref) refs.push(n.$ref);
    walk(n.then);
    walk(n.else);
  };
  walk(s.then);
  walk(s.else);
  return refs;
}

function typesFile(schema, hash) {
  const out = [header(SCHEMA_FILE, hash)];
  out.push(
    '/* eslint-disable */\n// Types of the pinned AWP schema. Conditional rules (if/then/else, not) are not expressed:\n' +
      '// the types are wider than the schema. The validator, not the type, decides.\n\n',
  );
  for (const [name, def] of Object.entries(schema.$defs)) {
    const refs = def.properties ? [] : conditionalRefs(def);
    const body = refs.length > 0 ? refs.map(refName).join(' | ') : tsType(def, '');
    out.push(`${doc(def.description, '')}export type Awp${name} = ${body};\n\n`);
  }
  out.push('/** Any manifest of the pinned schema (the three kinds). */\n');
  out.push('export type AwpManifest = AwpWorkflow | AwpAgent | AwpPolicy;\n');
  return out.join('');
}

function schemaFile(source, text, constName) {
  const hash = sha256(text);
  const body = JSON.stringify(JSON.parse(text), null, 2);
  return (
    header(source, hash) +
    '/* eslint-disable */\n' +
    `export const ${constName}_SHA256 = '${hash}';\n\n` +
    `export const ${constName}: Record<string, unknown> = ${body};\n`
  );
}

/** Computes the generated files (path relative to the repository root -> content). */
export function generate(root = REPO_ROOT, files = {}) {
  const schemaText = readFileSync(path.join(root, files.schema ?? SCHEMA_FILE), 'utf8');
  const extText = readFileSync(path.join(root, files.extensions ?? EXTENSIONS_FILE), 'utf8');
  const schema = JSON.parse(schemaText);
  return {
    [`${OUT_DIR}/awp-schema.ts`]: schemaFile(SCHEMA_FILE, schemaText, 'AWP_SCHEMA'),
    [`${OUT_DIR}/extensions-schema.ts`]: schemaFile(EXTENSIONS_FILE, extText, 'EXTENSIONS_SCHEMA'),
    [`${OUT_DIR}/awp-types.ts`]: typesFile(schema, sha256(schemaText)),
  };
}

/** @returns {number} exit code */
export function main(argv, out = { log: console.log, error: console.error }, root = REPO_ROOT) {
  const check = argv.includes('--check');
  const unknown = argv.filter((a) => a !== '--check');
  if (unknown.length > 0) {
    out.error(`usage: generate-types.mjs [--check] (unknown argument: ${unknown[0]})`);
    return 2;
  }
  const generated = generate(root);
  if (check) {
    const stale = [];
    for (const [file, content] of Object.entries(generated)) {
      let current = null;
      try {
        current = readFileSync(path.join(root, file), 'utf8');
      } catch {
        // missing counts as stale
      }
      if (current !== content) stale.push(file);
    }
    for (const file of stale) out.error(`stale or edited: ${file}`);
    if (stale.length > 0) out.error('run: node scripts/awp/generate-types.mjs');
    else out.log(`generated files are current (${Object.keys(generated).length})`);
    return stale.length > 0 ? 1 : 0;
  }
  mkdirSync(path.join(root, OUT_DIR), { recursive: true });
  for (const [file, content] of Object.entries(generated)) {
    writeFileSync(path.join(root, file), content);
    out.log(`wrote ${file}`);
  }
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exit(main(process.argv.slice(2)));
}
